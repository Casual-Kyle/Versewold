import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import { readFileSync, writeFileSync, mkdirSync, existsSync, renameSync } from 'node:fs';

// Compile the fixed schema at development time: native CSP never needs unsafe-eval.
const root = new URL('../src/domain/forms/', import.meta.url);
const schema = JSON.parse(readFileSync(new URL('poetry-form.schema.json', root), 'utf8'));
// Conditional required fields are declared on their parent meter object.
const ajv = new Ajv({
  allErrors: true,
  strict: true,
  strictRequired: false,
  code: { source: true, esm: true },
});
let source = standaloneCode(ajv, ajv.compile(schema));
// Ajv's standalone ESM still emits CommonJS helper imports. Convert those helpers
// to static imports so the same generated validator runs in Node and Vite.
source = source.replace(
  /const (\w+) = require\("([^"]+)"\)\.default;/g,
  (_, name, module) =>
    `import ${name}Module from '${module}.js'; const ${name} = ${name}Module.default ?? ${name}Module;`,
);
if (source.includes('require('))
  throw new Error('An unhandled standalone helper import needs conversion.');
mkdirSync(new URL('generated/', root), { recursive: true });
const destination = new URL('generated/validate.js', root);
const output = `// Generated by scripts/compile-form-schema.mjs. Do not edit.\n${source}\n`;
// Checks alongside tauri dev must not needlessly reload the writing workspace.
// Actual changes replace the validator atomically so Vite cannot read half a module.
if (!existsSync(destination) || readFileSync(destination, 'utf8') !== output) {
  const temporary = new URL(`generated/.validate-${process.pid}.tmp`, root);
  writeFileSync(temporary, output);
  renameSync(temporary, destination);
}
